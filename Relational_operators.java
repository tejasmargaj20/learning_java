
public class Relational_operators {
     public static void main(String[] args) {

        int num1 = 50;
        int num2 = 3;

        System.out.println(num1 == num2);

        System.out.println(num1 != num2);

        System.out.println(num1 < num2);

        System.out.println(num1 > num2);

        System.out.println(num1 <= num2);

        System.out.println(num1 >= num2);

}

}
